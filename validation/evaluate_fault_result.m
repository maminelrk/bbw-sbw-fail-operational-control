function [metrics,comparison] = evaluate_fault_result(result,nominal)
s=result.series; n=nominal.series(1:height(s),:); p=result.p; scenario=result.scenario;
assert(isequal(s.Time_s,n.Time_s),'Nominal and faulted time grids must match.');
physical=s{:,startsWith(s.Properties.VariableNames,'Physical_')};
known=s{:,startsWith(s.Properties.VariableNames,'Known_')};
onset=find(any(physical==0,2),1); flag=find(any(known==0,2),1);
assert(~isempty(onset) && ~isempty(flag),'Fault and diagnosis must occur in the record.');
tp=s.Time_s(onset); tf=s.Time_s(flag); post=s.Time_s>=tp;
window=post & s.Time_s<=tp+.2+1e-12;
err=max(abs([s.FxActual_N-s.OracleFx_N s.MzActual_Nm-s.OracleMz_Nm])./ ...
    [s.OracleScaleFx_N s.OracleScaleMz_Nm],[],2);
recovery=recovery_band_metric(s.Time_s,err,tf,.050,.100);
[crossTrack,covered]=path_deviation(s,nominal.series);
deceleration=max(0,-(s.FxActual_N/p.m+s.Vy_mps.*s.YawRate_radps));
commands=s{:,{'CmdFL_N','CmdFR_N','CmdRL_N','CmdRR_N'}};
knownFailed=known(:,1:4)==0;
isolation=all(abs(commands(knownFailed))<=1e-7);
diagnosed=find(all(physical==known,2) & s.Time_s>=tf,1);
activation=s.Time_s(diagnosed)-tf;
yawRMSE=sqrt(mean((s.YawRate_radps(post)-s.YawReference_radps(post)).^2));
pathPeak=max(abs(crossTrack(post))); yawJump=max(abs(s.YawRate_radps(window)-n.YawRate_radps(window)));
dbbs=scenario.FaultScenario=="steering_loss";
dbbsPass=covered && yawRMSE<=.03 && pathPeak<=.50 && max(deceleration(post))/p.g<=.35;
numerical=result.metrics.FinitePass && result.metrics.LoadPass && result.metrics.FrictionPass && ...
    result.metrics.RatePass && result.metrics.BoundsPass && result.metrics.SolverPass && ...
    result.metrics.OperatingPass && result.metrics.RateOverrideCount==0 && all(s.OracleExitFlag>0);
metrics=struct('ScenarioID',scenario.ID,'Fault',scenario.FaultScenario, ...
    'PhysicalOnset_s',tp,'FlagTime_s',tf,'DetectionDelay_s',tf-tp, ...
    'MaskActivation_s',activation,'MaskPass',activation<=.010 && isolation, ...
    'RecoveryDiagnostic_s',recovery.EntryDelay_s,'RecoveryDiagnosticPass',recovery.DiagnosticPass, ...
    'YawDifference200ms_radps',yawJump,'ContinuityDiagnosticPass',yawJump<=.05, ...
    'PostFaultYawRMSE_radps',yawRMSE,'PeakPathDeviation_m',pathPeak,'PathCoverage',covered, ...
    'PeakDeceleration_g',max(deceleration(post))/p.g, ...
    'FinalSpeedLoss_mps',n.Vx_mps(end)-s.Vx_mps(end), ...
    'HeldAngle_deg',rad2deg(s.Delta_rad(onset)), ...
    'NumericalChecksPass',numerical,'IsDBBS',dbbs,'DBBSManeuverPass',dbbs && dbbsPass, ...
    'REQ02Status',"PENDING_ENVELOPE_AND_ORACLE_REVIEW", ...
    'REQ03AuthorityStatus',"NOT_ASSESSED",'Gate3Closed',false);
comparison=table(s.Time_s,n.YawRate_radps,s.YawRate_radps,crossTrack, ...
    deceleration/p.g,err,'VariableNames',{'Time_s','NominalYaw_radps','FaultedYaw_radps', ...
    'CrossTrack_m','Deceleration_g','OracleNormalizedError'});
end
